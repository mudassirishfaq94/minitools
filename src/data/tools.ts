import type { ToolCategoryId, ToolMeta } from "@/types";

/** Every tool route lives under this prefix. */
export const TOOL_ROUTE_PREFIX = "/tool";

export function toolRoute(slug: string): string {
  return `${TOOL_ROUTE_PREFIX}/${slug}`;
}

type ToolInput = Omit<ToolMeta, "route" | "slug"> & { slug?: string };

/**
 * Normalizes a catalog entry: the slug defaults to the id and the route is
 * always derived from the slug, so links can never drift out of sync.
 */
function defineTool(tool: ToolInput): ToolMeta {
  const slug = tool.slug ?? tool.id;
  return { ...tool, slug, route: toolRoute(slug) };
}

